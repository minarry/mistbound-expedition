async function capture(name){
 const sizes = phoneRun ? [['mobile',baseSize]] : [['desktop',baseSize],['mobile',{width:390,height:844}]];
 for(const [label,size] of sizes){
  await page.setViewportSize(size);
  const frame = page.getByRole('region',{name:'雾境远征游戏视窗',exact:true});
  const rect = await frame.boundingBox();
  assert.ok(rect && rect.x>=0 && rect.y>=0 && rect.x+rect.width<=size.width+1 && rect.y+rect.height<=size.height+1,name+' inside viewport');
  assert.ok(await page.evaluate(()=>document.documentElement.scrollHeight<=innerHeight && document.documentElement.scrollWidth<=innerWidth),name+' must not scroll the document');
  await page.screenshot({path:'e2e/'+name+'-'+label+'.png',fullPage:true});
 }
 await page.setViewportSize(baseSize);
 console.log('Captured',name);
}
